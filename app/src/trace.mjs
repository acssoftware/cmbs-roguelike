// FOOTPRINTS — the debugging spine of the app.
//
// Rule: nothing important happens without a line in the log. Every file the app reads from the
// game, every file it writes, every call into `tools/re`, every decision the campaign engine
// takes, and every failure lands in `campaigns/<slug>/log.jsonl` as one JSON object per line.
// The lines carry a run id (one per server start) and a request id (one per API call), so a
// session can be replayed from the log alone.
//
// Why files are hashed: a bug report is useless if we cannot tell WHICH map, WHICH library
// source and WHICH generated battle produced it. `fileFacts` records path, size, mtime and
// sha256, so any battle can be regenerated byte for byte later.
//
// The log is written synchronously. Volumes are tiny (a few hundred lines per campaign) and a
// crash must not lose the line that explains it.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

export const RUN_ID = crypto.randomBytes(4).toString('hex');
let counter = 0;

const shortJson = (v) => {
  const s = JSON.stringify(v);
  return s === undefined ? '' : s.length > 220 ? s.slice(0, 217) + '...' : s;
};

export function fileFacts(file, { hash = true } = {}) {
  try {
    const st = fs.statSync(file);
    const facts = { path: file, bytes: st.size, mtime: st.mtime.toISOString() };
    if (hash && st.size <= 64 * 1024 * 1024) {
      facts.sha256 = crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex').slice(0, 16);
    }
    return facts;
  } catch (e) {
    return { path: file, missing: true, error: e.message };
  }
}

export class Trace {
  constructor(file, base = {}) {
    this.file = file;
    this.base = base;
    if (file) fs.mkdirSync(path.dirname(file), { recursive: true });
  }

  child(fields) {
    const t = new Trace(this.file, { ...this.base, ...fields });
    return t;
  }

  event(type, fields = {}) {
    const line = { t: new Date().toISOString(), seq: ++counter, run: RUN_ID, ...this.base, type, ...fields };
    if (this.file) {
      try { fs.appendFileSync(this.file, JSON.stringify(line) + '\n'); }
      catch (e) { process.stderr.write(`[trace] cannot write ${this.file}: ${e.message}\n`); }
    }
    const { t, seq, run, type: _t, ...rest } = line;
    process.stdout.write(`[${seq}] ${type} ${shortJson(rest)}\n`);
    // A BATERIA DE INTERRUPCOES (29/10): so no servidor do sandbox de QA, com CMBS_QA_DIE_AT, o processo morre logo depois
    // de gravar a linha do evento pedido ("tipo" ou "tipo:passo"), como se a janela do app fosse fechada naquele ponto.
    // Sem a variavel, nada muda.
    const alvo = process.env.CMBS_QA_DIE_AT;
    if (alvo && (alvo === type || alvo === `${type}:${fields.step}`)) { process.stdout.write(`[qa] morte em ${alvo}\n`); process.exit(137); }
    return line;
  }

  // A file the app READ from the game (or from assets). Recorded so a report identifies the input.
  read(label, file) { return this.event('file.read', { label, file: fileFacts(file) }); }

  // A file the app WROTE. Recorded so a report identifies the output.
  wrote(label, file) { return this.event('file.write', { label, file: fileFacts(file) }); }

  // Runs `fn`, timing it, logging start/ok/fail. `tools/re` prints its own diagnostics to stdout;
  // those lines are captured and stored with the step instead of being lost in the terminal.
  async step(name, fields, fn) {
    const started = Date.now();
    this.event('step.start', { step: name, ...fields });
    const lines = [];
    const real = { log: console.log, error: console.error, warn: console.warn };
    const grab = (...a) => { lines.push(a.map((x) => (typeof x === 'string' ? x : shortJson(x))).join(' ')); };
    console.log = grab; console.error = grab; console.warn = grab;
    try {
      const out = await fn();
      console.log = real.log; console.error = real.error; console.warn = real.warn;
      this.event('step.ok', { step: name, ms: Date.now() - started, output: lines });
      return out;
    } catch (e) {
      console.log = real.log; console.error = real.error; console.warn = real.warn;
      this.event('step.fail', { step: name, ms: Date.now() - started, output: lines, error: e.message, stack: String(e.stack || '').split('\n').slice(0, 12) });
      throw e;
    }
  }

  fail(where, error, context = {}) {
    return this.event('error', { where, message: error.message, stack: String(error.stack || '').split('\n').slice(0, 12), ...context });
  }

  tail(n = 200) {
    if (!this.file || !fs.existsSync(this.file)) return [];
    const all = fs.readFileSync(this.file, 'utf8').split('\n').filter(Boolean);
    return all.slice(-n).map((l) => { try { return JSON.parse(l); } catch { return { type: 'unparsable', raw: l }; } });
  }
}

// A trace that only writes to the console — used before a campaign folder exists.
export const consoleTrace = new Trace(null, {});
